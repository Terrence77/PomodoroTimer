<#
.SYNOPSIS
    Builds a signed Release MSIX of the Pomodoro Timer app.

.DESCRIPTION
    Uses the WinApp CLI (0.7+) project-mode packaging ('winapp package'), which publishes the
    app in Release (self-contained .NET and Windows App SDK, trimmed, ReadyToRun) and creates
    an MSIX signed with a local development certificate.

    The development certificate lives outside source control (certs\ is git-ignored). If it
    does not exist yet it is created with 'winapp cert generate' for the manifest's Publisher.
    This script never imports the certificate into a Windows certificate store; it prints the
    one-time elevated command to do that yourself.

    Certificate password, in order of precedence:
      1. -CertPassword parameter
      2. POMODORO_CERT_PASSWORD environment variable
      3. certs\devcert.password.txt (git-ignored; created with a random password when the
         certificate is generated by this script)

.PARAMETER Platform
    Target architecture: x64 or ARM64. Default: x64.

.PARAMETER CertPath
    Path to the signing .pfx. Default: <repo>\certs\devcert.pfx.

.PARAMETER CertPassword
    Password for the .pfx (see precedence above).

.OUTPUTS
    The signed .msix in <repo>\artifacts\. Exit code 0 on success, non-zero on failure.
#>
[CmdletBinding()]
param(
    [ValidateSet('x64', 'ARM64')]
    [string] $Platform = 'x64',

    [string] $CertPath,

    [string] $CertPassword
)

# Native commands (winapp) write progress to stderr; under Windows PowerShell 5.1 'Stop' would
# turn those lines into terminating errors when the caller redirects stderr. Check exit codes.
$ErrorActionPreference = 'Continue'

function Fail([string] $message) {
    Write-Host "Packaging FAILED: $message" -ForegroundColor Red
    exit 1
}

if (-not (Get-Command winapp -ErrorAction SilentlyContinue)) {
    Fail "WinApp CLI ('winapp') was not found on PATH. Install it (0.7 or later) and try again."
}

$repoRoot = $PSScriptRoot
$project = Join-Path $repoRoot 'src\PomodoroTimer\PomodoroTimer.csproj'
$manifestPath = Join-Path $repoRoot 'src\PomodoroTimer\Package.appxmanifest'
$certDir = Join-Path $repoRoot 'certs'
$artifactsDir = Join-Path $repoRoot 'artifacts'
if (-not $CertPath) { $CertPath = Join-Path $certDir 'devcert.pfx' }
$CertPath = [IO.Path]::GetFullPath($CertPath)
$passwordFile = Join-Path ([IO.Path]::GetDirectoryName($CertPath)) 'devcert.password.txt'
$cerPath = [IO.Path]::ChangeExtension($CertPath, '.cer')

# Package identity comes from the manifest so the printed commands stay in sync with it.
[xml] $manifest = Get-Content -LiteralPath $manifestPath -Raw
$identity = $manifest.Package.Identity
$packageName = $identity.Name
$publisher = $identity.Publisher
$version = $identity.Version
$arch = $Platform.ToLowerInvariant()

# Resolve the certificate password.
$passwordSource = $null
if ($CertPassword) {
    $passwordSource = '-CertPassword parameter'
} elseif ($env:POMODORO_CERT_PASSWORD) {
    $CertPassword = $env:POMODORO_CERT_PASSWORD
    $passwordSource = 'POMODORO_CERT_PASSWORD environment variable'
} elseif (Test-Path -LiteralPath $passwordFile) {
    $CertPassword = (Get-Content -LiteralPath $passwordFile -Raw).Trim()
    $passwordSource = $passwordFile
}

# Create the development certificate on first use.
if (-not (Test-Path -LiteralPath $CertPath)) {
    New-Item -ItemType Directory -Force -Path ([IO.Path]::GetDirectoryName($CertPath)) | Out-Null
    if (-not $CertPassword) {
        $bytes = New-Object byte[] 24
        [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
        $CertPassword = [Convert]::ToBase64String($bytes)
        [IO.File]::WriteAllText($passwordFile, $CertPassword)
        $passwordSource = "$passwordFile (newly generated)"
    }
    Write-Host "Creating development certificate for '$publisher' at $CertPath ..."
    # Generated in memory with an ephemeral key so nothing is written to any Windows
    # certificate store ('winapp cert generate' leaves a copy in CurrentUser\My).
    try {
        $rsa = New-Object Security.Cryptography.RSACng 3072
        $request = New-Object Security.Cryptography.X509Certificates.CertificateRequest(
            $publisher, $rsa,
            [Security.Cryptography.HashAlgorithmName]::SHA256,
            [Security.Cryptography.RSASignaturePadding]::Pkcs1)
        $request.CertificateExtensions.Add((New-Object Security.Cryptography.X509Certificates.X509BasicConstraintsExtension($false, $false, 0, $true)))
        $request.CertificateExtensions.Add((New-Object Security.Cryptography.X509Certificates.X509KeyUsageExtension(
            [Security.Cryptography.X509Certificates.X509KeyUsageFlags]::DigitalSignature, $true)))
        $ekus = New-Object Security.Cryptography.OidCollection
        $ekus.Add((New-Object Security.Cryptography.Oid('1.3.6.1.5.5.7.3.3', 'Code Signing'))) | Out-Null
        $request.CertificateExtensions.Add((New-Object Security.Cryptography.X509Certificates.X509EnhancedKeyUsageExtension($ekus, $false)))
        $now = [DateTimeOffset]::UtcNow
        $newCert = $request.CreateSelfSigned($now.AddMinutes(-5), $now.AddDays(365))
        [IO.File]::WriteAllBytes($CertPath, $newCert.Export([Security.Cryptography.X509Certificates.X509ContentType]::Pfx, $CertPassword))
        [IO.File]::WriteAllBytes($cerPath, $newCert.Export([Security.Cryptography.X509Certificates.X509ContentType]::Cert))
        $newCert.Dispose()
        $rsa.Dispose()
    } catch {
        Fail "Could not create the development certificate. $($_.Exception.Message)"
    }
}
if (-not $CertPassword) {
    Fail "No certificate password. Pass -CertPassword, set POMODORO_CERT_PASSWORD, or create $passwordFile."
}

# The signing certificate's subject must match the manifest Publisher exactly.
try {
    $cert = New-Object Security.Cryptography.X509Certificates.X509Certificate2($CertPath, $CertPassword)
} catch {
    Fail "Could not open $CertPath with the password from $passwordSource. $($_.Exception.Message)"
}
if ($cert.Subject -ne $publisher) {
    Fail "Certificate subject '$($cert.Subject)' does not match manifest Publisher '$publisher'."
}
if (-not (Test-Path -LiteralPath $cerPath)) {
    # Public-key-only copy used for the trust command below.
    [IO.File]::WriteAllBytes($cerPath, $cert.Export([Security.Cryptography.X509Certificates.X509ContentType]::Cert))
}

New-Item -ItemType Directory -Force -Path $artifactsDir | Out-Null
$msixPath = Join-Path $artifactsDir "PomodoroTimer_${version}_${arch}.msix"
if (Test-Path -LiteralPath $msixPath) { Remove-Item -LiteralPath $msixPath -Force }

Write-Host "Packaging Release MSIX for $Platform ..."
& winapp package $project -c Release --arch $arch --cert $CertPath --cert-password $CertPassword --output $msixPath
if ($LASTEXITCODE -ne 0) {
    Fail "winapp package failed (exit $LASTEXITCODE)."
}
if (-not (Test-Path -LiteralPath $msixPath)) {
    Fail "winapp package succeeded but $msixPath was not found."
}

$signature = Get-AuthenticodeSignature -LiteralPath $msixPath
if (-not $signature.SignerCertificate -or $signature.SignerCertificate.Thumbprint -ne $cert.Thumbprint) {
    Fail "$msixPath is not signed with $CertPath."
}

Write-Host ''
Write-Host "Signed MSIX: $msixPath" -ForegroundColor Green
Write-Host "Signer:      $($signature.SignerCertificate.Subject) ($($cert.Thumbprint))"
Write-Host "Signature:   $($signature.Status) (NotTrusted/UnknownError is expected until the certificate is trusted)"
Write-Host ''
Write-Host '1) Trust the development certificate (once per machine, in an elevated PowerShell):'
Write-Host "   Import-Certificate -FilePath '$cerPath' -CertStoreLocation Cert:\LocalMachine\TrustedPeople"
Write-Host ''
Write-Host '2) Remove a development registration of the same identity (from BuildAndRun.ps1 / RunUITests.ps1), if any:'
Write-Host "   Get-AppxPackage -Name '$packageName' | Where-Object { `$_.Publisher -eq '$publisher' -and `$_.IsDevelopmentMode } | Remove-AppxPackage"
Write-Host ''
Write-Host '3) Install the package:'
Write-Host "   Add-AppxPackage -Path '$msixPath'"
$cert.Reset()
exit 0
